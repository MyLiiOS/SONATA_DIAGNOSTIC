package ru.sonata.diagnostic.diagnostic.dtc

object DTCDatabase {

    private val descriptions = mapOf(
        "P0107" to "Низкий уровень сигнала датчика абсолютного давления во впускном коллекторе (MAP)",
        "P0106" to "Недостоверный диапазон или производительность датчика MAP",
        "P0108" to "Высокий уровень сигнала датчика MAP",
        "P0115" to "Неисправность цепи датчика температуры охлаждающей жидкости",
        "P0117" to "Низкий уровень сигнала датчика температуры охлаждающей жидкости",
        "P0118" to "Высокий уровень сигнала датчика температуры охлаждающей жидкости",
        "P0120" to "Неисправность цепи датчика положения дроссельной заслонки",
        "P0130" to "Неисправность цепи датчика кислорода",
        "P0171" to "Слишком бедная топливная смесь",
        "P0172" to "Слишком богатая топливная смесь",
        "P0300" to "Обнаружены случайные или множественные пропуски зажигания",
        "P0301" to "Пропуски зажигания в первом цилиндре",
        "P0302" to "Пропуски зажигания во втором цилиндре",
        "P0303" to "Пропуски зажигания в третьем цилиндре",
        "P0304" to "Пропуски зажигания в четвёртом цилиндре",
        "P0420" to "Эффективность системы нейтрализации ниже допустимого порога",
        "P0505" to "Неисправность системы регулирования холостого хода"
    )

    fun getDescription(code: String): String {
        return descriptions[code.uppercase()]
            ?: "Описание кода пока отсутствует в локальной базе"
    }

    fun contains(code: String): Boolean {
        return descriptions.containsKey(code.uppercase())
    }

    fun getAllCodes(): List<String> {
        return descriptions.keys.sorted()
    }
}
